// Practice 1: what division and the remainder print for whole numbers, a mixed pair and a negative number.
#include <iostream>

int main()
{
	std::cout << "7 / 2 = " << 7 / 2 << '\n';
	std::cout << "7 % 2 = " << 7 % 2 << '\n';
	std::cout << "7 / 2.0f = " << 7 / 2.0f << '\n';
	std::cout << "-7 / 2 = " << -7 / 2 << '\n';
	std::cout << "-7 % 2 = " << -7 % 2 << '\n';
	return 0;
}
