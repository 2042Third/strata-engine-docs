// The generated reference's files as the build reads them (plan/site.md, "Generated reference"; plan/pipelines.md §7.2;
// .tools/handover/reference-format.md). tools/reference.py render writes src/generated/reference/<table>.md from the
// engine at the pin; each file starts with a stamp that names the engine commit and the SHA-256 of the rest of the
// file, and holds no raw HTML but the closed block around a JSON schema, because engine text is escaped, never passed
// as HTML.

import { createHash } from 'node:crypto';

const c_Stamp = /^<!-- generated by tools\/reference\.py render ([^\s;]+); engine ([0-9a-f]{40}); sha256 ([0-9a-f]{64}); do not edit -->$/;

/** The SHA-256 a stamp names: of the UTF-8 bytes after the stamp line's newline. */
export function contentHash(rest) {
	return createHash('sha256').update(rest, 'utf8').digest('hex');
}

/** A generated file's text with its stamp, as tools/reference.py render writes it (for tests and fixtures). */
export function stampedFile(body, engine, version = '1') {
	return `<!-- generated by tools/reference.py render ${version}; engine ${engine}; sha256 ${contentHash(body)}; do not edit -->\n${body}`;
}

/**
 * Reads the stamp of a generated file: `{ version, engine, sha256, actual }`, where `actual` is the hash of what
 * follows the stamp; null when the first line is no stamp.
 */
export function readStamp(text) {
	const end = text.indexOf('\n');
	const match = c_Stamp.exec(end < 0 ? text : text.slice(0, end));
	if (!match) return null;
	return { version: match[1], engine: match[2], sha256: match[3], actual: contentHash(end < 0 ? '' : text.slice(end + 1)) };
}

/** What is wrong with a generated file's stamp for the engine commit `pin`, as messages (empty when nothing is). */
export function stampProblems(text, pin) {
	const stamp = readStamp(text);
	if (!stamp) return ['its first line is not the stamp of tools/reference.py render ("<!-- generated by tools/reference.py render <version>; engine <commit>; sha256 <hash>; do not edit -->"): run python -I tools/reference.py render; a generated file is never written by hand'];
	const problems = [];
	if (stamp.engine !== pin) problems.push(`it was rendered from engine ${stamp.engine}, but engine.pin names ${pin}: run python -I tools/reference.py dump, parse and render at the pin`);
	if (stamp.sha256 !== stamp.actual) problems.push('its content does not match the sha256 of its stamp, so it was edited by hand: run python -I tools/reference.py render and commit the result');
	return problems;
}

// The raw HTML a generated file may hold: the closed block around a schema, "<details>" with its "<summary>" (escaped
// text) and "</details>" (reference-format.md).
const c_SchemaOpen = /^<details>\s*<summary>[^<>]*<\/summary>$/;
const c_SchemaClose = /^<\/details>$/;

/** Whether a raw HTML node of a generated file is one the build accepts. */
export function allowedHtml(value) {
	const html = value.trim();
	return c_SchemaOpen.test(html) || c_SchemaClose.test(html);
}
