// The tables tools/reference.py render committed: the build reads them at the clone's pin as a page that includes every
// one of them would, so a change of render the build does not accept (a stamp, a hash, raw HTML, an escape that starts
// a directive) fails here before it fails a build.
test('every committed table of src/generated/reference/ passes the build at the clone\'s pin', async () => {
	const repository = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
	const folder = path.join(repository, 'src', 'generated', 'reference');
	const names = readdirSync(folder).filter((name) => name.endsWith('.md')).sort();
	assert.ok(names.length > 0, `${folder} holds no table`);
	const files = { 'engine.pin': readFileSync(path.join(repository, 'engine.pin'), 'utf8') };
	for (const name of names) files[`src/generated/reference/${name}`] = readFileSync(path.join(folder, name), 'utf8');
	const tables = book({ 'reference/performance': referencePage(names.map((name) => `::include{file="${name}"}`).join('\n\n')) }, files);
	try {
		const out = await render(tables.root, 'reference/performance');
		assert.equal(out.match(/<div class="book-reference" data-pagefind-weight="0\.3">/g)?.length, names.length);
		assert.doesNotMatch(out, /generated by tools\/reference\.py/);
		// The schema blocks render writes today (a command's parameter schema, a settings section's schema and its
		// default value) are closed blocks the build accepts. A command's example result comes with the first example a
		// tutorial run records (reference/_examples/), in the same block.
		for (const summary of ['Parameter schema of ', 'Schema of ', 'Default value of ']) {
			assert.match(out, new RegExp(`<details>\\s*<summary>${summary}[^<]+</summary>`), summary);
		}
	} finally {
		tables.remove();
	}
});
