// "::include{file=…}" (plan/site.md, "Generated reference"): a reference page puts a table of src/generated/reference/
// in its place, parsed with the book's Markdown, its headings anchored and seen by the page index, its content weighed
// less by search. The file's stamp names the pin and the hash of its content, and it holds no raw HTML but a closed
// schema block (.tools/handover/reference-format.md).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { allowedHtml, contentHash, readStamp, stampedFile, stampProblems } from '../../lib/reference.mjs';
import { prefixChapter } from '../../lib/print.mjs';
import { c_BottomStrip, c_ReferenceStrip, frontmatter, makeBook, rejectsWith, render } from './helpers.mjs';

const c_Commit = '822a7a46dbcdd86e8e2eafde7e41d003e27260c8';
const c_Body = '\n## Budgets\n\n| Test | Budget |\n| --- | --- |\n| `Perf.Scene.Update` | 2.0 ms |\n\n### The schema\n\n```json\n{ "budget": 2.0 }\n```\n';
const table = stampedFile(c_Body, c_Commit);
const referencePage = (body) => `${frontmatter({ kind: 'reference', tracks: '[]' })}\nThe table of every perf budget.\n\n${body}\n${c_ReferenceStrip}`;

function book(pages, files = { 'src/generated/reference/performance.md': table }) {
	return makeBook({ pages, files });
}

test('an included table is drawn in place, without its stamp, in an element search weighs less, with its headings anchored', async () => {
	const perf = book({
		'reference/performance': referencePage('::include{file="performance.md"}'),
		// Another page links a heading of the included table: the page index knows it.
		'core/time': `${frontmatter()}\nSee [the schema](../reference/performance.md#the-schema).\n${c_BottomStrip}`,
	});
	try {
		const out = await render(perf.root, 'reference/performance');
		assert.match(out, /<p>The table of every perf budget\.<\/p>\n<div class="book-reference" data-pagefind-weight="0\.3"><h2>Budgets<\/h2><table>/);
		assert.doesNotMatch(out, /generated by/);
		assert.match(out, /<td><code>Perf\.Scene\.Update<\/code><\/td>/);
		assert.match(out, /<h3>The schema<\/h3><pre><code class="language-json">/);
		assert.match(await render(perf.root, 'core/time'), /href="\/book\/reference\/performance\/#the-schema"/);
	} finally {
		perf.remove();
	}
});

test('a stamp names the version, the engine commit and the SHA-256 of everything after its line', () => {
	const stamp = readStamp(table);
	assert.deepEqual(stamp, { version: '1', engine: c_Commit, sha256: contentHash(c_Body), actual: contentHash(c_Body) });
	assert.match(table, /^<!-- generated by tools\/reference\.py render 1; engine 822a7a46dbcdd86e8e2eafde7e41d003e27260c8; sha256 [0-9a-f]{64}; do not edit -->\n\n## Budgets\n/);
	assert.deepEqual(stampProblems(table, c_Commit), []);
	// pipelines.md §7.2's shorter form names no hash: the files follow the form of reference-format.md.
	assert.equal(readStamp(`<!-- generated by tools/reference.py render from engine ${c_Commit}; do not edit -->\n${c_Body}`), null);
	assert.match(stampProblems('## Budgets\n', c_Commit)[0], /its first line is not the stamp of tools\/reference\.py render/);
	assert.match(stampProblems(stampedFile(c_Body, 'a'.repeat(40)), c_Commit)[0], /it was rendered from engine a{40}, but engine\.pin names 822a7a46/);
	assert.match(stampProblems(table.replace('2.0 ms', '2.5 ms'), c_Commit)[0], /its content does not match the sha256 of its stamp, so it was edited by hand/);
	// The hash covers the final newline too.
	assert.equal(stampProblems(table.replace(/\n$/, ''), c_Commit).length, 1);
});

test('a generated file\'s stamp must name the pin and match its content, or the page fails', async () => {
	const cases = [
		[c_Body, /reference\/performance\.md:14:1: src\/generated\/reference\/performance\.md: its first line is not the stamp of tools\/reference\.py render/],
		[stampedFile(c_Body, 'b'.repeat(40)), /src\/generated\/reference\/performance\.md: it was rendered from engine b{40}, but engine\.pin names 822a7a46dbcdd86e8e2eafde7e41d003e27260c8: run python -I tools\/reference\.py dump, parse and render at the pin/],
		[table.replace('Perf.Scene.Update', 'Perf.Scene.Draw'), /src\/generated\/reference\/performance\.md: its content does not match the sha256 of its stamp, so it was edited by hand/],
	];
	for (const [text, pattern] of cases) {
		const perf = book({ 'reference/performance': referencePage('::include{file="performance.md"}') }, { 'src/generated/reference/performance.md': text });
		try {
			await rejectsWith(render(perf.root, 'reference/performance'), pattern);
		} finally {
			perf.remove();
		}
	}
});

test('a schema stands in a closed <details>, which the print view opens; no other raw HTML stands in a generated file', async () => {
	const schema = '\n## Parameters\n\n| Name | Type |\n| --- | --- |\n| `entity` | string |\n\n<details>\n<summary>Parameters schema of entity.get</summary>\n\n```json\n{ "type": "object" }\n```\n\n</details>\n';
	const perf = book({ 'reference/performance': referencePage('::include{file="commands.md"}') }, { 'src/generated/reference/commands.md': stampedFile(schema, c_Commit) });
	try {
		const out = await render(perf.root, 'reference/performance');
		assert.match(out, /<\/table><details>\n<summary>Parameters schema of entity\.get<\/summary><pre><code class="language-json">\{ "type": "object" \}\n<\/code><\/pre><\/details><\/div>/);
		assert.doesNotMatch(out, /<details open/);
		assert.match(prefixChapter('<details><summary>Schema</summary><pre><code>{}</code></pre></details>', 'reference/commands', new Set(), '/book'), /<details open>/);
	} finally {
		perf.remove();
	}
	assert.equal(allowedHtml('<details>\n<summary>Parameters schema</summary>'), true);
	assert.equal(allowedHtml('<details><summary>Schema &amp; result</summary>'), true);
	assert.equal(allowedHtml('</details>'), true);
	for (const html of ['<details open>\n<summary>Schema</summary>', '<details>', '<summary>A</summary>', '<b>bold</b>', '<script>alert(1)</script>', '<details>\n<summary>A <b>b</b></summary>']) {
		assert.equal(allowedHtml(html), false, html);
	}
	const raw = stampedFile('\nThe engine says <b>hello</b>.\n\n<div class="x">A block.</div>\n', c_Commit);
	const unsafe = book({ 'reference/performance': referencePage('::include{file="unsafe.md"}') }, { 'src/generated/reference/unsafe.md': raw });
	try {
		const error = await rejectsWith(render(unsafe.root, 'reference/performance'), /a generated table holds no raw HTML but the closed <details> and <summary> around a schema/);
		// Each raw piece, with the file's line it stands on: the inline <b> and </b> (line 3) and the block (line 5).
		assert.match(error.message, /has 3 problems/);
		assert.match(error.message, /\(from src\/generated\/reference\/unsafe\.md:3:\d+\)/);
		assert.match(error.message, /\(from src\/generated\/reference\/unsafe\.md:5:1\)/);
	} finally {
		unsafe.remove();
	}
});

