test('an include stands only on reference pages and names an existing file of src/generated/reference/', async () => {
	const cases = [
		[{ 'core/time': `${frontmatter()}\n::include{file="performance.md"}\n${c_BottomStrip}` }, 'core/time', /::include stands only on pages of the part "reference", which hold the generated tables/],
		[{ 'reference/performance': referencePage('::include') }, 'reference/performance', /::include needs the file it reads: ::include\{file="<table>\.md"\}/],
		[{ 'reference/performance': referencePage('::include{file="../secrets.md"}') }, 'reference/performance', /::include\{file="\.\.\/secrets\.md"\}: name a file of src\/generated\/reference\/ by its path there/],
		[{ 'reference/performance': referencePage('::include{file="Performance.MD"}') }, 'reference/performance', /name a file of src\/generated\/reference\//],
		[{ 'reference/performance': referencePage('::include{file="missing.md"}') }, 'reference/performance', /::include\{file="missing\.md"\}: src\/generated\/reference\/missing\.md does not exist \(tools\/reference\.py render writes the generated tables\)/],
		[{ 'reference/performance': referencePage('::include{file="performance.md" weight=1}') }, 'reference/performance', /::include has no attribute "weight" \(it takes file\)/],
		[{ 'reference/performance': referencePage('::include[Budgets]{file="performance.md"}') }, 'reference/performance', /::include\[Budgets\] takes no text in brackets/],
	];
	for (const [pages, id, pattern] of cases) {
		const perf = book(pages);
		try {
			const error = await rejectsWith(render(perf.root, id), pattern).catch((failure) => {
				throw new Error(`${pattern}: ${failure.message}`);
			});
			// One problem, said once.
			assert.match(error.message, /has 1 problem:/);
		} finally {
			perf.remove();
		}
	}
});

test('a problem in an included table names the page\'s line and the file and line it comes from', async () => {
	const broken = stampedFile('The rows.\n\n:::pitfall\nOops.\n:::\n\n::include{file="other.md"}\n', c_Commit);
	const perf = book({ 'reference/performance': referencePage('::include{file="performance.md"}') }, { 'src/generated/reference/performance.md': broken, 'src/generated/reference/other.md': stampedFile('x\n', c_Commit) });
	try {
		const error = await rejectsWith(render(perf.root, 'reference/performance'), /unknown directive :::pitfall/, /a generated table includes no other file/);
		// The page's front matter is 10 lines and a blank line: the text is line 12, the directive line 14. The file's
		// stamp is its line 1.
		assert.match(error.message, /reference\/performance\.md:14:1: unknown directive :::pitfall: [^\n]* \(from src\/generated\/reference\/performance\.md:4:1\)/);
		assert.match(error.message, /reference\/performance\.md:14:1: a generated table includes no other file \(from src\/generated\/reference\/performance\.md:8:1\)/);
	} finally {
		perf.remove();
	}
});

