class UsageError(Exception):
    """An environment or usage problem: exit code 2."""


class Finding:
    def __init__(self, where, form, name, reason):
        self.where, self.form, self.name, self.reason = where, form, name, reason

    def __str__(self):
        return '%s: %s: %s: %s' % (self.where, self.form, self.name, self.reason)


def suggestion(name, candidates):
    close = difflib.get_close_matches(name, list(candidates), n=3, cutoff=0.6)
    return (' (did you mean %s?)' % ', '.join('`%s`' % item for item in close)) if close else ''


def read_json(path):
    try:
        with open(path, encoding='utf-8') as file:
            return json.load(file)
    except ValueError as error:
        raise UsageError('%s is not valid JSON: %s' % (path, error))


class Names:
    """The engine's names at the pin, from the dumps and the parsed tables (None where a table is missing)."""

    def __init__(self, dumps, pin):
        if not os.path.isdir(dumps):
            raise UsageError('no dumps at %s: run python -I tools/reference.py dump and parse at the pin' % dumps)
        self.missing = []
        tables = {}
        for name in c_Dumps:
            tables[name] = self.load(os.path.join(dumps, name + '.json'), pin, name + '.json')
        for name in c_Parsed:
            tables[name] = self.load(os.path.join(dumps, 'parsed', name + '.json'), pin, 'parsed/%s.json' % name)
        self.commands = None
        if tables['commands'] is not None:
            self.commands = {entry['name']: entry.get('parameters') or {} for entry in tables['commands']['result'].get('commands', [])}
            self.groups = {name.split('.')[0] for name in self.commands}
        self.components = None
        self.properties = {}
        if tables['components'] is not None:
            self.components = {}
            for component in tables['components']['result'].get('components', []):
                properties = {item['Name']: item for item in component.get('properties', [])}
                self.components[component['name']] = {'displayName': component.get('displayName'), 'category': component.get('category'),
                                                       'properties': properties}
                for name, item in properties.items():
                    self.properties.setdefault(name, []).append((component['name'], item))
        self.sections = None
        for name in ('settings', 'preferences'):
            if tables[name] is None:
                continue
            self.sections = self.sections or {}
            for section in tables[name]['result'].get('sections', []):
                schema = section.get('schema') or {}
                self.sections[section['id']] = {'title': section.get('title'), 'fields': schema.get('properties') or {}}
        self.tests = tables['tests']
        self.macros = set(tables['macros']['macros']) if tables['macros'] is not None else None
        self.stages = set(tables['frame-stages']['stages']) if tables['frame-stages'] is not None else None
        self.options = tables['options']['programs'] if tables['options'] is not None else None
        self.paths = None
        if tables['paths'] is not None:
            self.paths = set(tables['paths']['paths'])
            self.folders = set()
            for path in self.paths:
                parts = path.split('/')
                for index in range(1, len(parts)):
                    self.folders.add('/'.join(parts[:index]))
            self.submodules = tables['paths'].get('submodules', {})
            self.top_level = {path.split('/')[0] for path in self.paths} | {path.split('/')[0] for path in self.submodules}
        self.ui = None
        if tables['ui-literals'] is not None:
            self.ui = set(tables['ui-literals']['literals'])
            # A label drawn behind an icon is formatted as "{}  Mesh only": the reader sees the words after the icon.
            for literal in tables['ui-literals']['literals']:
                match = c_IconLabel.match(literal)
                if match:
                    self.ui.add(match.group(1))
            for component in (self.components or {}).values():
                if component['displayName']:
                    self.ui.add(component['displayName'])
                # Add Component groups the components under their categories' names (InspectorPanel.cpp).
                if component.get('category'):
                    self.ui.add(component['category'])
                for item in component['properties'].values():
                    if item.get('DisplayName'):
                        self.ui.add(item['DisplayName'])
                    self.ui.update(item.get('Options') or [])
            for section in (self.sections or {}).values():
                if section['title']:
                    self.ui.add(section['title'])
                self.ui.update(field.get('title') for field in section['fields'].values() if isinstance(field, dict) and field.get('title'))
            for name in ('templates', 'samples'):
                if tables[name] is not None:
                    self.ui.update(entry.get('name') for entry in tables[name]['result'].get(name, []) if entry.get('name'))

    def load(self, path, pin, label):
        if not os.path.isfile(path):
            self.missing.append(label)
            return None
        data = read_json(path)
        if not isinstance(data, dict) or data.get('pin') != pin:
            raise UsageError('%s holds the names of pin %s, but engine.pin names %s: run python -I tools/reference.py dump and '
                             'parse at the pin' % (path, data.get('pin') if isinstance(data, dict) else None, pin))
        return data

    def all_names(self):
        """Every engine name of the tables (for the spelling list)."""
        names = set()
        names.update(self.commands or {})
        for component, data in (self.components or {}).items():
            names.add(component)
            names.update(data['properties'])
        for section, data in (self.sections or {}).items():
            names.add(section)
            names.update(data['fields'])
        names.update(self.macros or ())
        names.update(self.stages or ())
        if self.tests:
            names.update(self.tests.get('suites', []))
            names.update(self.tests.get('ctest', []))
        for program, commands in (self.options or {}).items():
            names.add(program)
            for command, options in commands.items():
                names.add(command)
                names.update(options)
        names.update(self.paths or ())
        names.update(self.ui or ())
        return {name for name in names if isinstance(name, str) and name}


class Engine:
    """The pin clone read through git at the pin: literal searches and declarations, batched."""

    def __init__(self, path, pin):
        try:
            self.engine = repo.Engine(path)
            self.engine.resolve(pin)
        except repo.EngineError as error:
            raise UsageError('%s (pipelines.md §1.4, check 1)' % error)
        self.path = self.engine.path
        self.pin = pin
        self.found = {}
        self.declared = {}
        self.trees = {}

    def grep(self, arguments):
        result = subprocess.run(['git', '-C', self.path, 'grep', '-I', '--no-color'] + arguments + [self.pin, '--'],
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if result.returncode not in (0, 1):
            raise UsageError('git grep in %s: %s' % (self.path, result.stderr.decode('utf-8', 'replace').strip()))
        return result.stdout.decode('utf-8', 'replace').splitlines()

    def contains(self, names):
        """{name: True} for every name some file at the pin contains, in one git grep."""
        wanted = [name for name in names if name not in self.found]
        if wanted:
            with tempfile.NamedTemporaryFile('w', encoding='utf-8', suffix='.txt', delete=False) as file:
                file.write('\n'.join(wanted) + '\n')
            try:
                matches = set(self.grep(['-F', '-o', '-h', '-f', file.name]))
            finally:
                os.remove(file.name)
            for name in wanted:
                # A name that only occurs inside a longer name of the list is hidden by it in -o's output: ask again.
                self.found[name] = name in matches or bool(self.grep(['-F', '-l', '-e', name]))
        return {name: self.found[name] for name in names}

    def declaring(self, scope):
        """The files at the pin that declare the class, struct, enum or namespace `scope`."""
        if scope not in self.declared:
            # POSIX classes, not \b: git's extended regular expressions differ between builds (Git for Windows has no \b).
            pattern = r'(^|[^[:alnum:]_])(class|struct|enum|namespace)[[:space:]]+%s([^[:alnum:]_]|$)' % scope
            self.declared[scope] = sorted({line.split(':', 2)[1] for line in self.grep(['-l', '-E', '-e', pattern]) if line.count(':') >= 1})
        return self.declared[scope]

    def identifier_in(self, files, identifier):
        pattern = re.compile(r'\b%s\b' % re.escape(identifier))
        for path in files:
            lines = self.engine.read(self.pin, path)
            if lines is not None and any(pattern.search(line) for line in lines):
                return True
        return False

    def submodule_tree(self, submodule, commit):
        """The files of a vendor submodule at the commit the pin records, from its checkout in the clone."""
        if submodule not in self.trees:
            folder = os.path.join(self.path, *submodule.split('/'))
            result = subprocess.run(['git', '-C', folder, 'ls-tree', '-r', '--name-only', commit], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            if result.returncode != 0:
                raise UsageError('the submodule %s is not at %s in the clone %s: run git submodule update --init --recursive '
                                 '--depth 1 there (pipelines.md §1.3)' % (submodule, commit[:12], self.path))
            self.trees[submodule] = set(result.stdout.decode('utf-8', 'replace').splitlines())
        return self.trees[submodule]

    def close(self):
        self.engine.close()


def strip_span(text):
    """A code span's content as CommonMark reads it: one space on each side is removed when both are there."""
    if len(text) > 1 and text.startswith(' ') and text.endswith(' ') and text.strip():
        return text[1:-1]
    return text


class Tokens:
    """A reader of the parameters a page writes after a command: JSON, with keys that may be bare words, keys without
    a value ({path, overwrite}) and "…" for an elided value."""

    c_Token = re.compile(r'\s*(?:(?P<punct>[{}\[\]:,])|(?P<string>"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\')|(?P<number>-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)|'
                         r'(?P<ellipsis>…|\.\.\.)|(?P<word>[$A-Za-z_][\w$-]*))')

    def __init__(self, text):
        self.items = []
        position = 0
        text = text.strip()
        while position < len(text):
            match = self.c_Token.match(text, position)
            if not match or match.end() == position:
                raise ValueError('unexpected %r' % text[position:position + 10])
            position = match.end()
            kind = match.lastgroup
            value = match.group(kind)
            if kind == 'string':
                value = json.loads('"%s"' % value[1:-1].replace('"', '\\"')) if value[0] == "'" else json.loads(value)
            elif kind == 'number':
                value = float(value) if any(char in value for char in '.eE') else int(value)
            self.items.append((kind, value))
        self.index = 0

    def peek(self):
        return self.items[self.index] if self.index < len(self.items) else (None, None)

    def take(self, kind=None, value=None):
        token = self.peek()
        if token[0] is None or (kind and token[0] != kind) or (value is not None and token[1] != value):
            raise ValueError('expected %s' % (value or kind))
        self.index += 1
        return token

    def value(self):
        kind, value = self.peek()
        if kind == 'punct' and value == '{':
            self.take()
            result = {}
            while self.peek() != ('punct', '}'):
                key_kind, key = self.take()
                if key_kind not in ('word', 'string'):
                    raise ValueError('a key is a word or a string')
                if self.peek() == ('punct', ':'):
                    self.take()
                    result[key] = self.value()
                else:
                    result[key] = Ellipsis
                if self.peek() == ('punct', ','):
                    self.take()
                elif self.peek() != ('punct', '}'):
                    raise ValueError('expected "," or "}"')
            self.take('punct', '}')
            return result
        if kind == 'punct' and value == '[':
            self.take()
            result = []
            while self.peek() != ('punct', ']'):
                result.append(self.value())
                if self.peek() == ('punct', ','):
                    self.take()
                elif self.peek() != ('punct', ']'):
                    raise ValueError('expected "," or "]"')
            self.take('punct', ']')
            return result
        if kind == 'ellipsis':
            self.take()
            return Ellipsis
        if kind == 'word':
            self.take()
            return {'true': True, 'false': False, 'null': None}.get(value, value)
        if kind in ('string', 'number'):
            self.take()
            return value
        raise ValueError('expected a value')


def parse_parameters(text):
    tokens = Tokens(text)
    value = tokens.value()
    if tokens.peek()[0] is not None or not isinstance(value, dict):
        raise ValueError('the parameters are one object')
    return value


def schema_problems(value, schema, path, top=False):
    """What is wrong with a value against a command's parameter schema: keys that are no property, and values of a
    property with an enum that are not in it. Bound references ({"$ref": …}) and elided values pass."""
    if value is Ellipsis or not isinstance(schema, dict):
        return []
    for key in ('anyOf', 'oneOf'):
        if key in schema:
            branches = [schema_problems(value, branch, path) for branch in schema[key]]
            return [] if any(not problems for problems in branches) else branches[0]
    if isinstance(value, dict) and set(value) == {'$ref'}:
        return []
    problems = []
    if 'enum' in schema and not isinstance(value, (dict, list)) and value not in schema['enum']:
        problems.append('%s is %s; its values are %s' % (path or 'the value', json.dumps(value),
                                                         ', '.join(json.dumps(item) for item in schema['enum'])))
    if isinstance(value, dict) and isinstance(schema.get('properties'), dict):
        properties = schema['properties']
        for key, item in value.items():
            if key in properties:
                problems += schema_problems(item, properties[key], '%s.%s' % (path, key) if path else key)
            elif top or schema.get('additionalProperties') is False:
                problems.append('%s has no parameter "%s"%s; its parameters are %s' % (path or 'the command', key,
                                suggestion(key, properties), ', '.join(sorted(properties)) or 'none'))
    if isinstance(value, list) and isinstance(schema.get('items'), dict):
        for index, item in enumerate(value):
            problems += schema_problems(item, schema['items'], '%s[%d]' % (path, index))
    return problems


class PageNames:
    """The checks of one page."""

    def __init__(self, checker, page_id, path):
        self.checker = checker
        self.page_id = page_id
        self.where_file = checker.layout.relative(path)
        self.text = repo.read_text(path)
        data, _, _, _ = frontmatter.read(self.text)
        self.kind = (data or {}).get('kind')
        self.since = (data or {}).get('since')
        self.section = None
        self.lives = []  # (line, engine path) of the paths named under "Where it lives in Strata"
        self.findings = []
        self.scopes = []  # (line, name) of `A::B` spans, checked together

    def add(self, line, form, name, reason):
        self.findings.append(Finding('%s:%d' % (self.where_file, line), form, name, reason))

    def run(self):
        prose = markdown.prose_lines(self.text)
        in_step = False
        in_strip = False
        for number, line in prose:
            heading = re.match(r'^## (.*?)\s*$', line)
            if heading:
                self.section = heading.group(1)
                in_strip = heading.group(1) in c_StripSections
            ordered = c_OrderedItem.match(line)
            if ordered:
                in_step = not in_strip
            elif line.strip() and not line.startswith((' ', '\t')):
                in_step = False
            for match in c_Span.finditer(line):
                self.span(number, strip_span(match.group(2)))
            visible = c_Span.sub(lambda match: ' ' * len(match.group(0)), line)
            for match in c_Bold.finditer(visible):
                self.bold(number, match.group(1).strip(), in_step and self.kind in ('tutorial', 'how-to'))
        for fence in markdown.fences(self.text):
            if fence.lang.lower() in ('json', 'jsonc'):
                self.fence(fence)

    def span(self, line, text):
        names = self.checker.names
        if '\n' in text or not text.strip():
            return
        macro = c_Macro.match(text)
        if macro:
            return self.check_macro(line, macro.group(1))
        program = c_Program.match(text)
        if program and program.group('rest').strip():
            return self.check_program(line, program.group('program'), program.group('rest').split())
        with_parameters = c_CommandWithParameters.match(text)
        command = c_Command.match(text)
        if (with_parameters or (command and command.group('action') not in c_FileExtensions)) and self.checker.require('commands', 'commands') is None:
            return
        if with_parameters and with_parameters.group('name').split('.')[0] in names.groups:
            return self.check_command(line, with_parameters.group('name'), with_parameters.group('parameters'), text)
        if command and command.group('group') in names.groups and command.group('action') not in c_FileExtensions:
            if text not in names.commands:
                group = command.group('group')
                self.add(line, 'command', text, 'no registered command has this name%s; group %s has %s'
                         % (suggestion(text, names.commands), group,
                            ', '.join(sorted(name for name in names.commands if name.startswith(group + '.')))))
            return
        if '::' in text:
            scope = c_Scope.match(text)
            if scope:
                self.scopes.append((line, re.sub(r'<[^<>]*>', '', scope.group('name'))))
            return
        value = c_PropertyValue.match(text)
        if value:
            return self.check_property_value(line, value.group('property'), value.group('value').strip())
        if self.check_path(line, text):
            return
        three = c_Three.match(text)
        if three:
            return self.check_three(line, text, three.groups())
        two = c_Two.match(text)
        if two:
            return self.check_two(line, text, two.groups())

    def check_macro(self, line, macro):
        macros = self.checker.require('macros', 'macros')
        if macros is not None and macro.endswith('_'):
            # The start of a family's names (`ST_WITH_` followed by a module): some macro must start with it.
            if not any(name.startswith(macro) for name in macros):
                self.add(line, 'macro', macro, 'no macro at the pin starts with it%s' % suggestion(macro, macros))
            return
        if macros is not None and macro not in macros:
            self.add(line, 'macro', macro, 'no #define or CMake compile definition at the pin defines it%s' % suggestion(macro, macros))

    def check_program(self, line, program, words):
        options = self.checker.require('options', 'program options')
        if options is None:
            return
        known = options.get(program)
        if known is None:
            self.add(line, 'program option', program, 'parsed/options.json lists no options of this program')
            return
        command = ''
        if program == 'StrataCLI' and words and not words[0].startswith('-'):
            command = words[0]
            if command not in known:
                self.add(line, 'program option', '%s %s' % (program, command), 'StrataCLI has no command "%s"; its commands are %s'
                         % (command, ', '.join(sorted(name for name in known if name))))
                return
        for word in words:
            option = word.split('=', 1)[0]
            if option.startswith('--') and option not in known.get(command, []) and option not in known.get('', []):
                self.add(line, 'program option', '%s %s' % (program + (' ' + command if command else ''), option),
                         'not an option of %s%s%s' % (program, ' ' + command if command else '', suggestion(option, known.get(command, []))))

    def check_command(self, line, name, parameters, text):
        names = self.checker.names
        if name not in names.commands:
            self.add(line, 'command', name, 'no registered command has this name%s' % suggestion(name, names.commands))
            return
        try:
            value = parse_parameters(parameters)
        except ValueError as error:
            self.add(line, 'command parameters', text, 'the parameters are not an object of "key: value" pairs (%s): write '
                     '{key: value, …}' % error)
            return
        for problem in schema_problems(value, names.commands[name], '', top=True):
            self.add(line, 'command parameters', name, problem)

    def check_property_value(self, line, prop, value):
        components = self.checker.require('components', 'component properties')
        if components is None:
            return
        found = self.checker.names.properties.get(prop)
        if not found:
            self.add(line, 'property value', prop, 'no component has this property%s' % suggestion(prop, self.checker.names.properties))
            return
        literal = value.strip('"\'`')
        problems = []
        for component, item in found:
            if item.get('Type') == 'Enum' and literal not in (item.get('Options') or []):
                problems.append('%s.%s is one of %s' % (component, prop, ', '.join(item.get('Options') or [])))
            elif item.get('Type') == 'Bool' and literal not in ('true', 'false'):
                problems.append('%s.%s is true or false' % (component, prop))
            else:
                return
        self.add(line, 'property value', '%s = %s' % (prop, value), '; '.join(problems))

    def check_path(self, line, text):
        """True when the span is an engine path (and was checked)."""
        names = self.checker.names
        if re.search(r'\s', text) or '/' not in text and '.' not in text:
            return False
        if names.paths is None:
            self.checker.require('paths', 'engine paths')
            return False
        path = c_PathSuffix.sub('', text).rstrip('/')
        first = path.split('/')[0]
        if first not in names.top_level:
            return False
        if path in names.paths or path in names.folders:
            if self.section == c_WhereItLives:
                self.lives.append((line, path))
            return True
        if '*' in path or '?' in path:
            if any(fnmatch.fnmatchcase(candidate, path) for candidate in names.paths | names.folders):
                return True
        else:
            for submodule, commit in names.submodules.items():
                if path == submodule:
                    return True
                if path.startswith(submodule + '/'):
                    inner = path[len(submodule) + 1:]
                    tree = self.checker.engine.submodule_tree(submodule, commit) if self.checker.engine else set()
                    folders = {'/'.join(item.split('/')[:index]) for item in tree for index in range(1, item.count('/') + 1)}
                    if inner in tree or inner in folders:
                        return True
                    self.add(line, 'engine path', text, 'no file or folder of %s at the commit the pin records%s'
                             % (submodule, suggestion(inner, tree)))
                    return True
        self.add(line, 'engine path', text, 'no file or folder at the pin has this path%s' % suggestion(path, names.paths | names.folders))
        return True

    def check_three(self, line, text, words):
        names = self.checker.names
        section = '%s.%s' % words[:2]
        if names.sections is not None and section in names.sections and words[2] in names.sections[section]['fields']:
            return
        tests = self.checker.require('tests', 'doctest suites and CTest names')
        if tests is not None and (text in tests.get('suites', []) or text in tests.get('ctest', [])):
            return
        if names.sections is None or tests is None:
            return
        if section in names.sections:
            fields = names.sections[section]['fields']
            self.add(line, 'section field or test', text, 'section %s has no field %s%s; its fields are %s'
                     % (section, words[2], suggestion(words[2], fields), ', '.join(sorted(fields))))
        else:
            self.add(line, 'section field or test', text, 'neither a field of a settings or preferences section, a doctest '
                     'suite nor a CTest name at the pin%s' % suggestion(text, list(tests.get('suites', [])) + list(tests.get('ctest', []))))

    def check_two(self, line, text, words):
        names = self.checker.names
        # A stage or a test comes first: `World.Streaming` is a stage and `World.Coordinates` a doctest suite although
        # World is a component.
        stages = self.checker.require('frame-stages', 'frame profiler stages')
        if stages is not None and text in stages:
            return
        tests = self.checker.require('tests', 'doctest suites and CTest names')
        if tests is not None and (text in tests.get('suites', []) or text in tests.get('ctest', [])):
            return
        if names.components is not None and words[0] in names.components:
            properties = names.components[words[0]]['properties']
            if words[1] not in properties:
                self.add(line, 'component property', text, 'component %s has no property %s%s; its properties are %s'
                         % (words[0], words[1], suggestion(words[1], properties), ', '.join(sorted(properties))))
            return
        if names.sections is not None and text in names.sections:
            return
        if names.sections is None or tests is None or names.components is None or stages is None:
            return
        self.add(line, 'section or test', text, 'neither a settings or preferences section, a doctest suite, a CTest name nor a '
                 'frame profiler stage at the pin%s' % suggestion(text, list(names.sections) + list(tests.get('suites', []))
                                                                   + list(tests.get('ctest', [])) + list(stages)))

    def bold(self, line, text, in_step):
        if '▸' in text:
            ui = self.checker.require('ui-literals', 'UI names')
            if ui is None:
                return
            for part in (item.strip() for item in text.split('▸')):
                if part not in ui:
                    self.add(line, 'menu path', text, '"%s" is no UI name of the editor at the pin%s' % (part, suggestion(part, ui)))
            return
        if not in_step or c_KeyChord.match(text) or c_StepLabels.match(text) or self.checker.is_term(text):
            return
        ui = self.checker.require('ui-literals', 'UI names')
        if ui is not None and text not in ui:
            self.add(line, 'UI name', text, 'a bold span in a step names a UI label, and the editor at the pin has no "%s"%s; write '
                     'names the reader makes as code, and glossary terms as terms' % (text, suggestion(text, ui)))

    def fence(self, fence):
        try:
            data = json.loads(fence.text)
        except ValueError:
            return
        steps = data if isinstance(data, list) else [data]
        if not all(isinstance(step, dict) and isinstance(step.get('command'), str) for step in steps) or not steps:
            return
        if self.checker.require('commands', 'commands') is None:
            return
        commands = self.checker.names.commands
        for step in steps:
            name = step['command']
            offset = next((index for index, text in enumerate(fence.body) if '"%s"' % name in text), 0)
            line = fence.open_line + 1 + offset
            if name not in commands:
                self.add(line, 'command step', name, 'no registered command has this name%s' % suggestion(name, commands))
                continue
            for problem in schema_problems(step.get('parameters', {}), commands[name], '', top=True):
                self.add(line, 'command step', name, problem)


class Checker:
    def __init__(self, layout, names, engine, release):
        self.layout = layout
        self.names = names
        self.engine = engine
        self.release = release
        self.notes = []
        self.errors = []
        self.warnings = []
        self.reported = set()
        self.terms = set()
        try:
            with open(layout.glossary, encoding='utf-8') as file:
                for entry in json.load(file).get('terms', []):
                    for name in [entry.get('term')] + list(entry.get('aliases') or []):
                        if isinstance(name, str):
                            self.terms.add(name.lower())
        except FileNotFoundError:
            pass
        except ValueError as error:
            raise UsageError('%s is not valid JSON: %s' % (layout.glossary, error))

    def is_term(self, text):
        word = text.lower()
        return word in self.terms or (word.endswith('s') and word[:-1] in self.terms) or (word.endswith('es') and word[:-2] in self.terms)

    def require(self, table, what):
        """The table, or None after a note (an error with --release) that its forms are not checked."""
        value = {'macros': self.names.macros, 'frame-stages': self.names.stages, 'options': self.names.options, 'tests': self.names.tests, 'paths': self.names.paths,
                 'ui-literals': self.names.ui, 'components': self.names.components, 'commands': self.names.commands}[table]
        if value is None and table not in self.reported:
            self.reported.add(table)
            label = ('parsed/%s.json' % table) if table in c_Parsed else '%s.json' % table
            message = 'names: %s cannot be checked: the dumps lack %s; run python -I tools/reference.py dump and parse at the pin' % (what, label)
            (self.errors if self.release else self.notes).append(message)
        return value


def book_files(layout, page_id):
    """The page's own sketches and tutorial files: their texts."""
    part, _, chapter = page_id.partition('/')
    files = glob.glob(os.path.join(layout.sketches, '%s-%s-*' % (part, chapter)))
    folder = os.path.join(layout.tutorials, part, chapter)
    for base, _, names in os.walk(folder):
        files.extend(os.path.join(base, name) for name in names)
    texts = []
    for path in sorted(files):
        try:
            texts.append(repo.read_text(path))
        except (UnicodeDecodeError, OSError):
            continue
    return texts


c_NamesSection = 'Names of this page'
c_AllowedName = re.compile(r'^- `?(?P<name>[^`]+?)`?\s*:\s+(?P<reason>\S.*)$')


def allowed_names(layout, page_id):
    """The names a page may write that the pin does not define, each with its reason: those the reader makes up and
    those an exercise or the page's own patch adds. The clerk lists them in the page's notes file
    (plan/notes/<page>.md), in a section "## Names of this page", one line each: - `Name`: why the pin lacks it."""
    path = os.path.join(layout.root, 'plan', 'notes', *(page_id + '.md').split('/'))
    try:
        text = repo.read_text(path)
    except (OSError, UnicodeDecodeError):
        return set()
    allowed = set()
    inside = False
    for line in text.split('\n'):
        heading = re.match(r'^## (.*?)\s*$', line)
        if heading:
            inside = heading.group(1) == c_NamesSection
            continue
        match = c_AllowedName.match(line.strip()) if inside else None
        if match:
            allowed.add(match.group('name').strip())
    return allowed


def check_scopes(checker, pages):
    """`A::B`: in some file at the pin, in a file that declares A, or in the page's own sketches and tutorial files."""
    wanted = sorted({name for page in pages for _, name in page.scopes})
    if not wanted:
        return
    if checker.engine is None:
        raise UsageError('the page names `A::B` forms: pass --engine <the pin clone>')
    found = checker.engine.contains(wanted)
    for page in pages:
        own = None
        for line, name in page.scopes:
            if found[name]:
                continue
            scope, _, identifier = name.rpartition('::')
            last = scope.split('::')[-1]
            if checker.engine.identifier_in(checker.engine.declaring(last), identifier.lstrip('~')):
                continue
            if own is None:
                own = book_files(checker.layout, page.page_id)
            declares = re.compile(r'\b(class|struct|enum|namespace)\s+%s\b' % re.escape(last))
            ident = re.compile(r'\b%s\b' % re.escape(identifier.lstrip('~')))
            if any(name in text or (declares.search(text) and ident.search(text)) for text in own):
                continue
            page.add(line, 'scope name', name, 'no file at the pin contains it, no file declaring %s holds %s, and the page\'s '
                     'sketches and tutorial files do not define it' % (last, identifier))


def check(layout, dumps, engine_path, page_ids, release):
    """(findings, notes, errors)."""
    pin = repo.read_pin(layout.pin_file)['commit']
    names = Names(dumps, pin)
    engine = Engine(engine_path, pin) if engine_path else None
    try:
        checker = Checker(layout, names, engine, release)
        all_pages = dict(layout.pages())
        page_ids = [repo.named_page(page_id) for page_id in page_ids]
        for page_id in page_ids:
            if page_id not in all_pages:
                raise UsageError('no page %s (src/content/docs/%s.md)' % (page_id, page_id))
        pages = []
        for page_id, path in sorted(all_pages.items()):
            if page_ids and page_id not in page_ids:
                continue
            page = PageNames(checker, page_id, path)
            page.run()
            pages.append(page)
        check_scopes(checker, pages)
        check_since(checker, pages, repo.read_pin(layout.pin_file).get('release'))
        findings = []
        for page in pages:
            allowed = allowed_names(layout, page.page_id)
            findings.extend(finding for finding in page.findings if finding.name not in allowed)
        return findings, checker.notes + ['%s (warning)' % warning for warning in checker.warnings], checker.errors
    finally:
        if engine is not None:
            engine.close()


def release_tuple(text):
    match = re.match(r'^(\d+)\.(\d+)\.(\d+)$', text or '')
    return tuple(int(part) for part in match.groups()) if match else None


def check_since(checker, pages, release):
    """style.md §6.1: a page whose "Where it lives in Strata" engine files are all absent at v0.7.0 and whose `since`
    is older than the book's release is reported (a warning: the files may have moved)."""
    candidates = [page for page in pages if page.lives and isinstance(page.since, str) and release_tuple(page.since)
                  and release_tuple(release) and release_tuple(page.since) < release_tuple(release)]
    if not candidates or checker.engine is None:
        return
    try:
        tag = checker.engine.engine.resolve(c_SinceTag)
    except repo.EngineError:
        checker.notes.append('names: "since" cannot be compared with %s: the clone has no tag %s; run git fetch --tags in it '
                             '(pipelines.md §1.3)' % (c_SinceTag, c_SinceTag))
        return
    for page in candidates:
        if all(not checker.engine.engine.exists(tag, path) for _, path in page.lives):
            line = page.lives[0][0]
            checker.warnings.append(Finding('%s:%d' % (page.where_file, line), 'since', page.since,
                                            'every file "## %s" names is absent at %s, so the subject looks new in %s: write '
                                            'since: %s, or name the files it had before' % (c_WhereItLives, c_SinceTag, release, release)))


def find_typos(root):
    found = shutil.which('typos')
    if found:
        return found
    for candidate in sorted(glob.glob(os.path.join(root, '.tools', 'typos-*', 'typos*'))):
        if os.path.basename(candidate) in ('typos', 'typos.exe'):
            return candidate
    return None


def flagged_words(typos, words, folder):
    """The words typos flags among `words`, lowercased, with its own dictionary only (no configuration file)."""
    path = os.path.join(folder, 'words.txt')
    with open(path, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(sorted(words)) + '\n')
    result = subprocess.run([typos, '--isolated', '--format', 'json', 'words.txt'], cwd=folder, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if result.returncode not in (0, 2):
        raise UsageError('typos failed: %s' % result.stderr.decode('utf-8', 'replace').strip())
    flagged = set()
    for line in result.stdout.decode('utf-8', 'replace').splitlines():
        if line.strip().startswith('{'):
            record = json.loads(line)
            if record.get('type') == 'typo':
                flagged.add(record['typo'].lower())
    return flagged


def spelling_words(layout, plan, dumps, book=outline_rules.c_Book):
    """The candidates: the words of the outline's page ids and, with dumps, the engine names."""
    outline = outline_rules.read(plan, book)
    if outline.problems:
        raise UsageError('the outline has %d problems (python plan/check_outline.py lists them); fix them first' % len(outline.problems))
    words = set()
    for page in outline.pages:
        words.update(part for part in re.split(r'[/-]', page.id) if part)
    if dumps:
        pin = repo.read_pin(layout.pin_file)['commit']
        for name in Names(dumps, pin).all_names():
            # typos skips what looks like a path, so a path's words are given one by one, without their extensions.
            if '/' in name:
                words.update(os.path.splitext(part)[0] for part in name.split('/') if os.path.splitext(part)[0])
            else:
                words.add(name)
    return words


def split_block(text):
    """(before, block lines, after) of _typos.toml; block None when the markers are absent."""
    lines = text.split('\n')
    starts = [index for index, line in enumerate(lines) if line.startswith('# generated by tools/names.py spelling')]
    ends = [index for index, line in enumerate(lines) if line.strip() == c_BlockEnd]
    if not starts and not ends:
        return lines, None, []
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise UsageError('_typos.toml must hold the generated block\'s two marker lines once each, in order')
    return lines[:starts[0]], lines[starts[0] + 1:ends[0]], lines[ends[0] + 1:]


def listed_elsewhere(lines):
    """The words the rest of _typos.toml lists under [default.extend-words] (lowercased)."""
    words = set()
    table = None
    for line in lines:
        header = re.match(r'^\s*\[([^\]]+)\]\s*$', line)
        if header:
            table = header.group(1).strip()
            continue
        entry = re.match(r'^\s*"?([^"=\s]+)"?\s*=', line)
        if table == 'default.extend-words' and entry:
            words.add(entry.group(1).lower())
    return words


def spelling_text(text, flagged):
    """_typos.toml with its generated block holding the flagged words the rest of the file does not list."""
    before, block, after = split_block(text)
    rest = before + after
    words = sorted(word for word in flagged if word not in listed_elsewhere(rest))
    body = [c_BlockStart] + ['%s = "%s"' % (word if re.match(r'^[a-z0-9_-]+$', word) else json.dumps(word), word) for word in words] + [c_BlockEnd]
    if block is not None:
        return '\n'.join(before + body + after)
    headers = [line.strip() for line in before if re.match(r'^\s*\[[^\]]+\]\s*$', line)]
    if not headers or headers[-1] != '[default.extend-words]':
        raise UsageError('_typos.toml has no generated block and does not end in [default.extend-words]: add the lines "%s" and '
                         '"%s" inside that table' % (c_BlockStart, c_BlockEnd))
    while before and not before[-1].strip():
        before.pop()
    return '\n'.join(before + body) + '\n'


def spelling(layout, plan, dumps, write, book=outline_rules.c_Book):
    typos = find_typos(layout.root)
    if typos is None:
        raise UsageError('the spelling list needs typos: python tools/bootstrap.py puts it into .tools/')
    path = os.path.join(layout.root, '_typos.toml')
    text = repo.read_text(path)
    folder = tempfile.mkdtemp(prefix='names-spelling-')
    try:
        expected = spelling_text(text, flagged_words(typos, spelling_words(layout, plan, dumps, book), folder))
    finally:
        shutil.rmtree(folder, ignore_errors=True)
    if write:
        if expected != text:
            repo.write_text(path, expected)
        print('names: wrote the generated block of _typos.toml (%d words)' % len(split_block(expected)[1]))
        return 0
    if expected != text:
        before, block, _ = split_block(text)
        line = len(before) + 1
        print('_typos.toml:%d: the generated block is not what the page ids%s give today: run python -I tools/names.py spelling '
              '--write%s' % (line, ' and the engine names' if dumps else '', ' --dumps <the dumps>' if dumps else ''))
        return 1
    print('names: the generated block of _typos.toml is current')
    return 0


