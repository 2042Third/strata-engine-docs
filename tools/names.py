#!/usr/bin/env python3
"""The names lint (plan/pipelines.md §8): every engine name a page writes, checked against the engine at the pin.

    python -I tools/names.py check [--release] --dumps reference/_dumps/<pin> --engine <clone> [pages...]
    python -I tools/names.py spelling (--write | --check) [--dumps reference/_dumps/<pin>]

check     Reads the pages' prose and their JSON fences, the dumps, the parsed tables, and the trees of the pin and of
          the vendor submodules, and prints "<page>:<line>: <form>: <name>: <reason>" for each name that is not the
          engine's. It exits 1 on any finding. It is a writer's exit check, a site check, and part of what the
          technical reviewer receives. The forms (pipelines.md §8):
            `<group>.<action>` (a command group of the dump)  a registered command            commands.json
            `<command> {…}`                                   its keys and enum values        commands.json
            a JSON fence of command steps                     the same, for each step         commands.json
            `<Component>.<Property>` (a registered component) the property exists             components.json
            `<Property> = <value>`                            a property; Enum and Bool value components.json
            `<A>.<B>` of two capitalized words                a section, a doctest suite, settings.json,
                                                              a CTest name or a frame         preferences.json, tests,
                                                              profiler stage                  parsed/frame-stages.json
            `<A>.<B>.<C>` of three capitalized words          a field of section <A>.<B>, a   settings.json, tests
                                                              doctest suite or a CTest name
            `ST_…`                                            a macro defined at the pin      parsed/macros.json
            `ST_…_` (the start of a family of names)          a macro at the pin starts with  parsed/macros.json
                                                              it
            `<A>::<B>`                                        in a file at the pin, in a file the engine; the page's
                                                              declaring <A>, or in the page's sketches and tutorials
                                                              own sketches or tutorial files
            `StrataEditor --<option>`, `StrataRuntime --…`,   an option of that program       parsed/options.json
            `StrataCLI <command> --<option>`
            an engine path (its first part is a top-level     a file or folder at the pin, or parsed/paths.json and
            entry of the engine)                              of a vendor submodule's tree    the submodules
            **Menu ▸ Item ▸ …**                               each part is a UI name          the UI names
            a bold span in a numbered step of a tutorial or   a UI name                       the UI names
            how-to page that is not a glossary term
          UI names are the literals of parsed/ui-literals.json and the names the UI shows from registries: the
          components' displayNames and categories, the properties' DisplayNames and Options, the sections' and
          fields' titles, and the template and sample names; a literal "{}  Words" (an icon before a label) also
          gives "Words". Without --release, a table the dumps lack is a note and its forms are not
          checked; with --release it is an error. A page whose "Where it lives in Strata" files are all absent at
          v0.7.0 while its `since` is older than the book's release is a warning (style.md §6.1).
spelling  Writes (--write) or checks (--check) the generated block of _typos.toml: the words of the outline's page ids
          and, with --dumps, of the engine names above, that the pinned typos would flag (rulings 5, R17). The block
          stands between the lines "# generated by tools/names.py spelling …" and "# end of the generated block"
          inside [default.extend-words]; a word the rest of the file already lists is left out.

The dumps are reference.py's (pipelines.md §7.2): {commands, preferences, templates, samples, settings, components}.json,
each {"pin", "engineCommit", "command", "result"}. The parsed tables this tool reads, each {"pin", …}:
  parsed/macros.json       {"macros": ["ST_CORE_ASSERT", …]}: every macro named ST_… that a #define or a CMake
                           compile definition (target_compile_definitions, add_compile_definitions) at the pin defines
  parsed/tests.json        {"suites": [doctest suites], "ctest": [CTest names]}
  parsed/options.json      {"programs": {"StrataEditor": {"": [options]}, "StrataRuntime": {"": […]},
                            "StrataCLI": {"": [options without a command], "<command>": [its options], …}}}
  parsed/paths.json        {"paths": [every file of git ls-tree -r <pin>], "submodules": {"<path>": "<commit>", …}}
  parsed/frame-stages.json {"stages": ["GPU.AO", "Render.Extract", …]}: the frame profiler's stages at the pin
                           (c_BuiltinFrameStages, RegisterStage, RegisterGPUStage, ST_PROFILE_STAGE, ProfileStage)
  parsed/ui-literals.json  {"literals": [the C++ string literals of the editor's UI, adjacent ones joined, ## suffixes
                            removed]}
Every file's "pin" must be engine.pin's commit. --engine is the pin clone; the tool reads it at the pin through git
(pipelines.md §1.2) and stops with exit code 2 when it does not have the pin (§1.4, check 1).

Only the standard library is used. Exit codes: 0 when all is well, 1 when findings were found, 2 for usage or
environment errors.
"""

